def handle_capture_refunded(notification: PaymentWebhookNotification) -> bool:
    """PAYMENT.CAPTURE.REFUNDED — merchant- or API-initiated refund.

    Per the PayPal webhook catalog the resource is a v2 Refund object. The
    ``status`` field carries the life cycle state (COMPLETED, PENDING,
    CANCELLED, FAILED); pending/failed refunds are NOT separate event types.
    """
    resource = notification.body.get("resource")
    if not isinstance(resource, dict):
        logger.warning("PAYMENT.CAPTURE.REFUNDED: missing resource")
        return False
    order = _find_order_for_v2_refund(resource)
    if not order:
        logger.warning(
            "PAYMENT.CAPTURE.REFUNDED for refund %s: no matching order",
            resource.get("id"),
        )
        return False
    _apply_v2_refund(order, resource, reversal=False)
    order.save()
    return True


def handle_capture_reversed(notification: PaymentWebhookNotification) -> bool:
    """PAYMENT.CAPTURE.REVERSED — PayPal-initiated reversal (chargeback outcome).

    Despite the event name the resource PayPal attaches is a v2 Refund object
    (confirmed by real sanitized payloads such as
    https://github.com/woocommerce/woocommerce-paypal-payments/issues/1614).
    """
    resource = notification.body.get("resource")
    if not isinstance(resource, dict):
        logger.warning("PAYMENT.CAPTURE.REVERSED: missing resource")
        return False
    order = _find_order_for_v2_refund(resource)
    if not order:
        logger.warning(
            "PAYMENT.CAPTURE.REVERSED for refund %s: no matching order",
            resource.get("id"),
        )
        return False
    _apply_v2_refund(order, resource, reversal=True)
    order.save()
    return True


def handle_sale_refunded_v1(notification: PaymentWebhookNotification) -> bool:
    """PAYMENT.SALE.REFUNDED — legacy v1 sale-world refund event.

    PayPal may still emit v1 events for some merchants even on v2 integrations.
    The v1 resource uses different field names (``state`` lowercase,
    ``amount.total``/``amount.currency``, ``custom``/``invoice_number``,
    ``sale_id``/``parent_payment``) — normalize here and reuse the v2
    side-effects machinery.
    """
    resource = notification.body.get("resource")
    if not isinstance(resource, dict):
        logger.warning("PAYMENT.SALE.REFUNDED: missing resource")
        return False
    order = _find_order_for_v1_sale(resource)
    if not order:
        logger.warning(
            "PAYMENT.SALE.REFUNDED for refund %s: no matching order",
            resource.get("id"),
        )
        return False

    v1_amount = resource.get("amount") or {}
    normalized = {
        "id": resource.get("id"),
        "status": _V1_STATE_TO_V2_STATUS.get((resource.get("state") or "").lower(), "COMPLETED"),
        "amount": {
            "value": v1_amount.get("total") or "0",
            "currency_code": v1_amount.get("currency") or "USD",
        },
        "custom_id": resource.get("custom"),
        "invoice_id": resource.get("invoice_number"),
        "create_time": resource.get("create_time"),
        "update_time": resource.get("update_time"),
        "_source": "v1_sale_refund",
    }
    _apply_v2_refund(order, normalized, reversal=False)
    order.save()
    return True


def _find_order_for_v2_capture(resource: dict) -> Order | None:
    """Resolve the Order for a v2 capture resource (PAYMENT.CAPTURE.COMPLETED /
    PAYMENT.CAPTURE.DENIED).
    """
    order = _find_order_by_reference(resource.get("invoice_id"))
    if order:
        return order
    order = _find_order_by_reference(resource.get("custom_id"))
    if order:
        return order
    return _find_order_by_capture_id(resource.get("id"))


def handle_capture_completed(notification: PaymentWebhookNotification) -> bool:
    """PAYMENT.CAPTURE.COMPLETED — primary payment capture confirmation.

    The synchronous capture in :func:`registration.paypal_payments.capture_paypal_payment`
    already sets ``Order.status = COMPLETED`` for the happy path. This handler
    is a safety net for captures that PayPal initially returned as PENDING
    (held for review, pending eCheck, etc.) and later cleared. Transitions
    PENDING -> COMPLETED and enqueues the registration email if one has not
    yet been sent.
    """
    resource = notification.body.get("resource")
    if not isinstance(resource, dict):
        logger.warning("PAYMENT.CAPTURE.COMPLETED: missing resource")
        return False
    order = _find_order_for_v2_capture(resource)
    if not order:
        logger.warning(
            "PAYMENT.CAPTURE.COMPLETED for capture %s: no matching order",
            resource.get("id"),
        )
        return False

    if order.status == Order.COMPLETED:
        return True

    if order.status in (
        Order.REFUNDED,
        Order.REFUND_PENDING,
        Order.DISPUTE_EVIDENCE_REQUIRED,
        Order.DISPUTE_PROCESSING,
        Order.DISPUTE_WON,
        Order.DISPUTE_LOST,
        Order.DISPUTE_ACCEPTED,
    ):
        logger.warning(
            "PAYMENT.CAPTURE.COMPLETED for order %s ignored: terminal status %s",
            order.reference,
            order.status,
        )
        return True

    previous_status = order.status
    order.status = Order.COMPLETED
    order.save()

    if previous_status == Order.PENDING and order.email_sent is None and order.billingEmail:
        try:
            tasks.send_registration_email_task.delay(order.id, order.billingEmail)  # ty:ignore[unresolved-attribute]
        except Exception:
            logger.exception(
                "Failed to queue registration email for late-completed order %s",
                order.id,  # ty:ignore[unresolved-attribute]
            )
    return True


def handle_capture_denied(notification: PaymentWebhookNotification) -> bool:
    """PAYMENT.CAPTURE.DENIED — capture was denied by PayPal.

    Mark the Order as FAILED so admins see it in reconciliation dashboards.
    Idempotent: no-op if the order is already FAILED.
    """
    resource = notification.body.get("resource")
    if not isinstance(resource, dict):
        logger.warning("PAYMENT.CAPTURE.DENIED: missing resource")
        return False
    order = _find_order_for_v2_capture(resource)
    if not order:
        logger.warning(
            "PAYMENT.CAPTURE.DENIED for capture %s: no matching order",
            resource.get("id"),
        )
        return False
    if order.status != Order.FAILED:
        order.status = Order.FAILED
        order.save()
    return True


def _add_attendees_to_banlist_and_hold(order: Order) -> None:
    dispute_hold = get_hold_type("Chargeback")
    for oi in OrderItem.objects.filter(order=order):
        attendee = oi.badge.attendee
        attendee.holdType = dispute_hold
        attendee.save()
        BanList.objects.get_or_create(
            email=attendee.email,
            defaults=dict(
                firstName=attendee.firstName,
                lastName=attendee.lastName,
                reason=f"Initiated chargeback [APIS {datetime.now().isoformat()}]",
            ),
        )


def handle_dispute_created(notification: PaymentWebhookNotification) -> bool:
    """CUSTOMER.DISPUTE.CREATED — buyer filed a dispute. Mark evidence required,
    apply a chargeback hold and ban-list entry to each attendee on the order,
    and queue the admin-notification email.
    """
    resource = notification.body.get("resource")
    if not isinstance(resource, dict):
        logger.warning("CUSTOMER.DISPUTE.CREATED: missing resource")
        return False
    order = _find_order_for_dispute(resource)
    if not order:
        logger.warning(
            "CUSTOMER.DISPUTE.CREATED for dispute %s: no matching order",
            resource.get("dispute_id"),
        )
        return False
    if not isinstance(order.apiData, dict):
        order.apiData = {}
    order.apiData["dispute"] = resource  # ty:ignore[invalid-assignment]
    order.status = Order.DISPUTE_EVIDENCE_REQUIRED
    order.save()
    _add_attendees_to_banlist_and_hold(order)
    try:
        tasks.send_chargeback_notice_email_task.delay(order.id)  # ty:ignore[unresolved-attribute]
    except Exception:
        # Queue backend may be down at webhook-receive time. The dispute
        # state is already persisted to the Order; log and continue so the
        # webhook is marked processed. Ops can re-trigger the email later.
        logger.exception("Failed to queue chargeback notice email for order %s", order.id)  # ty:ignore[unresolved-attribute]
    return True


def handle_dispute_updated(notification: PaymentWebhookNotification) -> bool:
    """CUSTOMER.DISPUTE.UPDATED — status/evidence/message change. Refresh stored
    dispute snapshot; do not re-apply holds (they were applied on CREATED).
    """
    resource = notification.body.get("resource")
    if not isinstance(resource, dict):
        logger.warning("CUSTOMER.DISPUTE.UPDATED: missing resource")
        return False
    order = _find_order_for_dispute(resource)
    if not order:
        logger.warning(
            "CUSTOMER.DISPUTE.UPDATED for dispute %s: no matching order",
            resource.get("dispute_id"),
        )
        return False
    if not isinstance(order.apiData, dict):
        order.apiData = {}
    order.apiData["dispute"] = resource  # ty:ignore[invalid-assignment]
    # Only flip to DISPUTE_PROCESSING when dispute is actively being worked on
    # by PayPal (buyer awaiting response, under review); preserve terminal
    # statuses set by the RESOLVED handler.
    if order.status not in (
        Order.DISPUTE_WON,
        Order.DISPUTE_LOST,
        Order.DISPUTE_ACCEPTED,
    ):
        status_value = (resource.get("status") or "").upper()
        if status_value in ("UNDER_REVIEW", "WAITING_FOR_BUYER_RESPONSE"):
            order.status = Order.DISPUTE_PROCESSING
    order.save()
    return True


def handle_dispute_resolved(notification: PaymentWebhookNotification) -> bool:
    """CUSTOMER.DISPUTE.RESOLVED — terminal. Map outcome_code to the matching
    Order.DISPUTE_* status. Reset donations when the outcome drops the order
    total (DISPUTE_LOST / DISPUTE_ACCEPTED).
    """
    resource = notification.body.get("resource")
    if not isinstance(resource, dict):
        logger.warning("CUSTOMER.DISPUTE.RESOLVED: missing resource")
        return False
    order = _find_order_for_dispute(resource)
    if not order:
        logger.warning(
            "CUSTOMER.DISPUTE.RESOLVED for dispute %s: no matching order",
            resource.get("dispute_id"),
        )
        return False
    if not isinstance(order.apiData, dict):
        order.apiData = {}
    order.apiData["dispute"] = resource  # ty:ignore[invalid-assignment]
    outcome = (resource.get("dispute_outcome") or {}).get("outcome_code") or ""
    order.status = _DISPUTE_OUTCOME_TO_ORDER_STATUS.get(outcome, Order.DISPUTE_PROCESSING)
    if order.status in (Order.DISPUTE_LOST, Order.DISPUTE_ACCEPTED) and (
        order.orgDonation > 0 or order.charityDonation > 0  # ty:ignore[unsupported-operator]
    ):
        order.notes = (order.notes or "") + (
            f"\n\nOriginal charity donation of ${order.charityDonation} and "
            f"organization donation of ${order.orgDonation} were reset due to "
            "lost or accepted dispute state."
        )
        order.orgDonation = Decimal("0")
        order.charityDonation = Decimal("0")
    order.save()
    return True
